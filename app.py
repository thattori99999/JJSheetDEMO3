# 各行のテキストを数値化して投資家にとって有利なセル(最小値・最大値)を返すパーサー
def extract_min_max_indices(row, mode="min"):
    vals = []
    
    # row が pandas.Series または Python の標準リストいずれであっても対応
    is_series = hasattr(row, 'iloc')
    length = len(row)
    
    # 1列目は項目名なので除外し、各ファンドの列を評価
    for i in range(1, length):
        val_str = str(row.iloc[i]).strip() if is_series else str(row[i]).strip()
        if not val_str or "記載なし" in val_str or "抽出スキップ" in val_str:
            continue
            
        # 🌟 無料（手数料ゼロ）を意味するキーワード。
        # ユーザー指摘の「かかりません」を筆合に、不要、発生、無料、なし、ゼロなどを徹底網羅
        free_keywords = ["なし", "無料", "ゼロ", "ノーロード", "かかりません", "発生しません", "不要", "負担いただきません", "かからず", "かかりません。"]
        if any(keyword in val_str for keyword in free_keywords) or val_str == "0" or val_str == "0.0":
            val = 0.0
            vals.append((i, val))
            continue
            
        # 1. パーセンテージ表記（%の直前にある数値）を最優先で抽出
        pct_matches = re.findall(r"([-+]?\d*\.\d+|\d+)\s*[%％]", val_str)
        if pct_matches:
            val = float(pct_matches[0])
            vals.append((i, val))
            continue
            
        # 2. パーセンテージ表記（%）が直接見つからない場合は、一般的な数値を抽出（小数値を優先）
        matches = re.findall(r"[-+]?\d*\.\d+|\d+", val_str)
        if matches:
            decimals = [float(m) for m in matches if '.' in m]
            if decimals:
                val = decimals[0]
            else:
                val = float(matches[0])
            vals.append((i, val))
        
    if not vals:
        return []
        
    # ベストパフォーマンス値（リターン is 最大値、コスト・手数料は最小値）を算出
    if mode == "min":
        best_val = min(v[1] for v in vals)
    else:
        best_val = max(v[1] for v in vals)
        
    # ベストパフォーマンス値を保持しているすべての列インデックスのリストを特定
    best_indices = [v[0] for v in vals if v[1] == best_val]
    
    return best_indices


