def extract_first_percent(text):
    """文字列中から最初に出現する『%の数値』を抽出。無料系キーワードの場合は0.0を返す。見つからない場合はNoneを返す。"""
    if not text:
        return None
    val_str = str(text).strip()
    free_keywords = ["なし", "無料", "ゼロ", "ノーロード", "かかりません", "発生しません", "不要", "負担いただきません", "かからず"]
    if any(k in val_str for k in free_keywords):
        return 0.0
    matches = re.findall(r"([-+]?\d*\.\d+|\d+)\s*[%％]", val_str)
    if matches:
        try:
            return float(matches[0])
        except ValueError:
            return None
    return None


def compute_effective_cost(purchase_fee_text, trust_fee_text):
    """購入時手数料と信託報酬（年率）を「見た目の実質コスト」として1つの文字列にまとめる。
    ※あくまで概算の目安であり、購入時手数料（一時的）と信託報酬（継続的）を単純合算した参考値である旨を明記する。"""
    purchase_pct = extract_first_percent(purchase_fee_text)
    trust_pct = extract_first_percent(trust_fee_text)

    if purchase_pct is not None and trust_pct is not None:
        total = purchase_pct + trust_pct
        return f"目安 {total:.3f}%（購入時{purchase_pct:g}% + 信託報酬{trust_pct:g}%）"
    elif trust_pct is not None:
        return f"信託報酬 年{trust_pct:g}%（購入時手数料：記載なし）"
    elif purchase_pct is not None:
        return f"購入時{purchase_pct:g}%（信託報酬：記載なし）"
    else:
        return "記載なし（抽出スキップ）"


def simplify_nisa(nisa_text):
    """詳細なNISA区分の文言から『対象の有無』のみを簡潔に判定して返す。"""
    if not nisa_text:
        return "記載なし（抽出スキップ）"
    text = str(nisa_text).strip()
    if "記載なし" in text or "抽出スキップ" in text:
        return text
    no_keywords = ["対象外", "対象ではありません", "適用されません", "非対象", "なし"]
    if any(k in text for k in no_keywords) and not any(k in text for k in ["つみたて", "成長投資枠"]):
        return "対象外"
    # 対象の場合、可能であれば枠の種類も併記する
    types = []
    if "つみたて" in text:
        types.append("つみたて投資枠")
    if "成長投資枠" in text:
        types.append("成長投資枠")
    if types:
        return "対象（" + "・".join(types) + "）"
    return "対象"


