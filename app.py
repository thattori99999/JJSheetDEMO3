# AIの出力ゆらぎから「ファンドA」「ファンドB」などの仮名を完全排除するための自動置換フィルター
def replace_dummy_fund_names(text, selected_funds):
    if not selected_funds:
        return text
    
    # 完全にファンド名を一致させるため、一般的なゆらぎ表現を順次置換するリストを定義
    # 1番目のファンドに対応するダミー仮名
    dummies_a = [
        "ファンド名A", "ファンド A", "ファンドA", "Aファンド", "aファンド", 
        "ファンドa", "ファンド a", "ファンド（A）", "ファンド (A)", "（A）"
    ]
    # 2番目のファンドに対応するダミー仮名
    dummies_b = [
        "ファンド名B", "ファンド B", "ファンドB", "Bファンド", "bファンド", 
        "ファンドb", "ファンド b", "ファンド（B）", "ファンド (B)", "（B）"
    ]
    
    # 最も長い文字列パターンから安全に置換をかけます
    for d in dummies_a:
        text = text.replace(d, selected_funds[0])
        
    if len(selected_funds) > 1:
        for d in dummies_b:
            text = text.replace(d, selected_funds[1])
            
    return text


# JSON内のオブジェクトを含むすべてのネスト構造を再帰的に走査し、仮名を排除するフィルター
def clean_dummy_names_in_data(data, selected_funds):
    if not selected_funds:
        return data
        
    if isinstance(data, dict):
        new_data = {}
        for k, v in data.items():
            new_k = replace_dummy_fund_names(k, selected_funds)
            new_v = clean_dummy_names_in_data(v, selected_funds)
            new_data[new_k] = new_v
        return new_data
    elif isinstance(data, list):
        return [clean_dummy_names_in_data(item, selected_funds) for item in data]
    elif isinstance(data, str):
        return replace_dummy_fund_names(data, selected_funds)
        
    return data


